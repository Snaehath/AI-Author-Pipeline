"""
Dataset Loader & Tokenizer Module for Training.

Loads JSONL SFT datasets generated by Module 8 and formats examples into ChatML prompts
ready for causal language modeling fine-tuning.
"""

import sys
try:
    import pyarrow
except OSError:
    sys.modules["pyarrow"] = None

import json
from pathlib import Path
from typing import List, Dict, Any, Optional
from AI_Author.utils.logger import setup_logger

logger = setup_logger("AI_Author.Trainer.DatasetLoader")


def format_chatml_prompt(example: Dict[str, Any]) -> str:
    """Formats an SFT dataset line into Qwen ChatML template format.

    Args:
        example: Dictionary containing system, instruction, input, output.

    Returns:
        Formatted ChatML string.
    """
    sys_msg = example.get("system", "You are a professional AI novel author.")
    instruction = example.get("instruction", "")
    inp = example.get("input", "")
    output = example.get("output", "")

    user_msg = f"{instruction}\n\n{inp}".strip() if inp else instruction

    prompt = (
        f"<|im_start|>system\n{sys_msg}<|im_end|>\n"
        f"<|im_start|>user\n{user_msg}<|im_end|>\n"
        f"<|im_start|>assistant\n{output}<|im_end|>"
    )
    return prompt


def load_sft_jsonl_raw(jsonl_path: Path) -> List[Dict[str, Any]]:
    """Loads raw JSONL SFT dataset entries into a list of dictionaries.

    Args:
        jsonl_path: Path to train.jsonl or val.jsonl.

    Returns:
        List of raw dataset dictionaries.
    """
    path = Path(jsonl_path)
    if not path.exists():
        raise FileNotFoundError(f"SFT Dataset file not found at: {path}")

    entries = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line_str = line.strip()
            if line_str:
                entries.append(json.loads(line_str))

    logger.info(f"Loaded {len(entries)} SFT examples from '{path.name}'.")
    return entries


def load_and_tokenize_sft_dataset(
    jsonl_path: Path,
    tokenizer: Optional[Any] = None,
    max_seq_length: int = 512,
) -> Any:
    """Loads JSONL dataset and converts to Hugging Face Dataset format if dependencies are available.

    Args:
        jsonl_path: Path to jsonl dataset file.
        tokenizer: Optional AutoTokenizer instance.
        max_seq_length: Token length cutoff.

    Returns:
        Hugging Face Dataset or list of formatted prompt dicts.
    """
    raw_entries = load_sft_jsonl_raw(jsonl_path)
    formatted_prompts = [format_chatml_prompt(entry) for entry in raw_entries]

    try:
        from datasets import Dataset

        data_dict = {"text": formatted_prompts}
        hf_dataset = Dataset.from_dict(data_dict)
        logger.info(f"Converted {len(formatted_prompts)} prompts to Hugging Face Dataset object.")
        return hf_dataset
    except ImportError:
        logger.warning("'datasets' package not installed. Returning raw text prompt list.")
        return [{"text": p} for p in formatted_prompts]
