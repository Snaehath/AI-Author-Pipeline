def build_contrastive_record(record: dict[str, Any]) -> dict[str, Any]:
    """
    Construct a human-grounded contrastive record from an audit record.
    """
    aid = record["audit_id"]
    src_text = record["source_text"]
    ha = record["human_audit"]
    det = record.get("detector_prediction", {})

    gold_primary = ha["primary_mechanism"]
    gold_secondary = ha.get("secondary_mechanisms", [])
    gold_horizon = ha.get("mechanism_horizon", "LOCAL")
    notes = ha.get("notes", "")

    det_prim = det.get("primary_mechanism")

    # Determine tempting alternative with strict priority on Tier 1 and Tier 2 confusion hubs:
    # 1. Direct Tier 1 / Tier 2 attractors present in secondary mechanisms or detector errors
    if gold_primary == "VERBAL_WIT" and ("DEADPAN_REACTION" in gold_secondary or det_prim == "DEADPAN_REACTION"):
        tempting = "DEADPAN_REACTION"
    elif gold_primary == "DEADPAN_REACTION" and ("VERBAL_WIT" in gold_secondary or det_prim == "VERBAL_WIT"):
        tempting = "VERBAL_WIT"
    elif gold_primary == "ESCALATION" and ("DEADPAN_REACTION" in gold_secondary or det_prim == "DEADPAN_REACTION"):
        tempting = "DEADPAN_REACTION"
    elif gold_primary == "ESCALATION" and ("VERBAL_WIT" in gold_secondary or det_prim == "VERBAL_WIT"):
        tempting = "VERBAL_WIT"
    elif gold_primary == "DIALOGUE_SUBTEXT" and ("DEADPAN_REACTION" in gold_secondary or det_prim == "DEADPAN_REACTION"):
        tempting = "DEADPAN_REACTION"
    elif gold_primary == "DRAMATIC_IRONY" and ("VERBAL_WIT" in gold_secondary or det_prim == "VERBAL_WIT"):
        tempting = "VERBAL_WIT"
    elif det_prim and det_prim != gold_primary:
        tempting = det_prim
    elif "DEADPAN_REACTION" in gold_secondary and gold_primary != "DEADPAN_REACTION":
        tempting = "DEADPAN_REACTION"
    elif "VERBAL_WIT" in gold_secondary and gold_primary != "VERBAL_WIT":
        tempting = "VERBAL_WIT"
    elif gold_secondary:
        tempting = gold_secondary[0]
    else:
        tempting = "VERBAL_WIT" if gold_primary != "VERBAL_WIT" else "DEADPAN_REACTION"

    # Lookup or construct contrastive profile
    pair_key = (gold_primary, tempting)
    template = CONTRASTIVE_TEMPLATES.get(pair_key)

    if template:
        surface_cue = template["surface_cue"]
        why_tempting = template["why_alternative_is_tempting"]
        counterfactual = template["counterfactual_test"]
        why_wins = template["why_primary_wins"]
    else:
        surface_cue = f"The passage presents prominent stylistic cues associated with {tempting}."
        why_tempting = f"The salient surface tone or dialogue structure superficially resembles {tempting}."
        counterfactual = f"Removing the stylistic markers of {tempting} preserves the comedic effectiveness of {gold_primary}; whereas removing the core {gold_primary} dynamic destroys the humor."
        why_wins = f"The fundamental causal engine generating the comedic effect is {gold_primary}, while {tempting} is secondary or incidental."

    # Incorporate human auditor notes into causal_mechanism
    causal_explanation = notes if notes else f"The comedic engine is driven by {gold_primary.lower().replace('_', ' ')}."

    contrastive_analysis = {
        "primary_mechanism": gold_primary,
        "causal_mechanism": causal_explanation,
        "surface_cue": surface_cue,
        "tempting_alternative": tempting,
        "why_alternative_is_tempting": why_tempting,
        "counterfactual_test": counterfactual,
        "why_primary_wins": why_wins,
    }

    return {
        "audit_id": aid,
        "source_book": record.get("source_book", "Unknown"),
        "source_text": src_text,
        "contrastive_analysis": contrastive_analysis,
        "secondary_mechanisms": gold_secondary,
        "setup_payoff_horizon": gold_horizon,
        "human_audit": ha,
    }


def build_contrastive_dataset(
    audit_path: Path = DEFAULT_AUDIT_PATH,
    test_path: Path = DEFAULT_TEST_PATH,
    dev_path: Path = DEFAULT_DEV_PATH,
    out_path: Path = DEFAULT_OUT_PATH,
    manifest_path: Path = DEFAULT_MANIFEST_PATH,
    report_manifest_path: Path = DEFAULT_REPORT_MANIFEST_PATH,
) -> dict[str, Any]:
    """
    Build the contrastive training dataset with strict exclusion of TEST and DEV.
    """
    with open(audit_path, encoding="utf-8") as f:
        raw_audit = json.load(f)

    with open(test_path, encoding="utf-8") as f:
        test_ids = {json.loads(line)["audit_id"] for line in f if line.strip()}
    with open(dev_path, encoding="utf-8") as f:
        dev_ids = {json.loads(line)["audit_id"] for line in f if line.strip()}

    # Assert invariant counts
    if len(test_ids) != 17:
        raise ValueError(f"Expected 17 TEST IDs, got {len(test_ids)}")
    if len(dev_ids) != 20:
        raise ValueError(f"Expected 20 DEV IDs, got {len(dev_ids)}")

    # Pool of eligible records: KEEP records not in TEST and not in DEV
    available_records = [
        r for r in raw_audit
        if r.get("human_audit", {}).get("keep_verdict") == "KEEP"
        and r["audit_id"] not in test_ids
        and r["audit_id"] not in dev_ids
    ]

    # Invariant: 106 KEEP - 17 TEST - 20 DEV = 69 available
    if len(available_records) != 69:
        raise ValueError(f"Expected 69 available KEEP records, found {len(available_records)}")

    # Sort available records deterministically by sft_score descending, then audit_id
    scored_pool = []
    for r in available_records:
        score_info = compute_sft_score(r)
        scored_pool.append((score_info["sft_score"], r["audit_id"], r))

    scored_pool.sort(key=lambda x: (-x[0], x[1]))

    # Prioritize Tier 1 and Tier 2 confusion pairs
    tier1_pairs = {("VERBAL_WIT", "DEADPAN_REACTION"), ("DEADPAN_REACTION", "VERBAL_WIT"),
                   ("ESCALATION", "DEADPAN_REACTION"), ("ESCALATION", "VERBAL_WIT")}
    tier2_pairs = {("DIALOGUE_SUBTEXT", "DEADPAN_REACTION"), ("DRAMATIC_IRONY", "VERBAL_WIT")}

    tier1_records = []
    tier2_records = []
    tier3_records = []

    for score, aid, r in scored_pool:
        contrastive_rec = build_contrastive_record(r)
        gold = contrastive_rec["contrastive_analysis"]["primary_mechanism"]
        tempting = contrastive_rec["contrastive_analysis"]["tempting_alternative"]
        pair = (gold, tempting)

        if pair in tier1_pairs:
            tier1_records.append(contrastive_rec)
        elif pair in tier2_pairs:
            tier2_records.append(contrastive_rec)
        else:
            tier3_records.append(contrastive_rec)

    # Select balanced, high-yield training set (48 records):
    # - All Tier 1 records available (highest priority confusion attractors)
    # - All Tier 2 records available
    # - High-scoring Tier 3 records to ensure full taxonomy coverage
    selected_train = []
    selected_train.extend(tier1_records)
    selected_train.extend(tier2_records)

    # Fill remaining from Tier 3 up to 48 records
    remaining_needed = 48 - len(selected_train)
    selected_train.extend(tier3_records[:remaining_needed])

    # Sort final training records by audit_id for absolute determinism
    selected_train.sort(key=lambda x: x["audit_id"])
    train_ids = {r["audit_id"] for r in selected_train}

    # Verify zero leakage invariants
    test_leakage = train_ids & test_ids
    dev_leakage = train_ids & dev_ids

    if test_leakage:
        raise RuntimeError(f"CRITICAL: Contrastive train leaks into TEST! Leaked IDs: {test_leakage}")
    if dev_leakage:
        raise RuntimeError(f"CRITICAL: Contrastive train leaks into DEV! Leaked IDs: {dev_leakage}")

    # Write datasets/sft/comedy_contrastive_train.jsonl
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        for r in selected_train:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    train_sha256 = compute_sha256(out_path)

    # Confusion pairs distribution
    confusion_pairs = Counter(
        f"{r['contrastive_analysis']['primary_mechanism']} -> {r['contrastive_analysis']['tempting_alternative']}"
        for r in selected_train
    )
    primary_dist = Counter(r["contrastive_analysis"]["primary_mechanism"] for r in selected_train)
    source_books = Counter(r["source_book"] for r in selected_train)

    manifest = {
        "phase": "4B-2",
        "dataset": "comedy_contrastive_train.jsonl",
        "role": "Contrastive & Counterfactual Supervision Training Set",
        "count": len(selected_train),
        "sha256": train_sha256,
        "source": {
            "audit_file": str(audit_path),
            "audited_records": len(raw_audit),
            "total_keep_records": 106,
            "test_count": len(test_ids),
            "dev_count": len(dev_ids),
            "available_pool_count": len(available_records),
        },
        "invariants": {
            "test_overlap_count": len(test_leakage),
            "dev_overlap_count": len(dev_leakage),
            "zero_leakage_verified": True,
            "all_records_human_grounded": True,
        },
        "primary_mechanism_distribution": dict(primary_dist),
        "confusion_pair_distribution": dict(confusion_pairs),
        "source_book_distribution": dict(source_books),
        "tier_breakdown": {
            "tier1_count": len(tier1_records),
            "tier2_count": len(tier2_records),
            "tier3_count": len(selected_train) - len(tier1_records) - len(tier2_records),
        },
        "train_audit_ids": [r["audit_id"] for r in selected_train],
    }

    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    with open(manifest_path, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2, ensure_ascii=False)

    report_manifest_path.parent.mkdir(parents=True, exist_ok=True)
    with open(report_manifest_path, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2, ensure_ascii=False)

    return manifest


def main() -> None:
    parser = argparse.ArgumentParser(description="Build Phase 4B-2 Contrastive Training Dataset.")
    parser.add_argument("--audit-path", type=Path, default=DEFAULT_AUDIT_PATH)
    parser.add_argument("--test-path", type=Path, default=DEFAULT_TEST_PATH)
    parser.add_argument("--dev-path", type=Path, default=DEFAULT_DEV_PATH)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT_PATH)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST_PATH)
    parser.add_argument("--report-manifest", type=Path, default=DEFAULT_REPORT_MANIFEST_PATH)
    args = parser.parse_args()

    manifest = build_contrastive_dataset(
        audit_path=args.audit_path,
        test_path=args.test_path,
        dev_path=args.dev_path,
        out_path=args.out,
        manifest_path=args.manifest,
        report_manifest_path=args.report_manifest,
    )

    print("=" * 60)
    print("Phase 4B-2 Contrastive Training Dataset Successfully Built")
    print("=" * 60)
    print(f"  Count:       {manifest['count']} records")
    print(f"  SHA-256:     {manifest['sha256']}")
    print(f"  Leakage:     TEST={manifest['invariants']['test_overlap_count']}, DEV={manifest['invariants']['dev_overlap_count']}")
    print("  Tier Breakdown:")
    for t, c in manifest["tier_breakdown"].items():
        print(f"    {t:15s}: {c}")
    print("  Top Confusion Pairs:")
    for p, c in sorted(manifest["confusion_pair_distribution"].items(), key=lambda x: -x[1])[:8]:
        print(f"    {p:35s}: {c}")
    print("=" * 60)


if __name__ == "__main__":
    main()
